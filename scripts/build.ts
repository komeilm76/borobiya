#!/usr/bin/env bun
/**
 * Builds every browser artifact:
 *   1. the Vue/Vuetify/Tailwind bundle through Vite,
 *   2. the service worker from `src/client/service-worker/sw.ts`,
 *   3. generated fonts, icons, logo and the deterministic cache manifest.
 *
 * Run through Bun only (`bun run build`).
 */
import { build } from 'vite';
import { buildAssets } from './build-assets.ts';

/**
 * Compiles the TypeScript service worker into the browser-required `public/sw.js`.
 *
 * @returns The byte size of the generated worker.
 */
export async function buildServiceWorker(): Promise<number> {
  const result = await Bun.build({
    entrypoints: ['src/client/service-worker/sw.ts'],
    target: 'browser',
    format: 'iife',
    minify: false,
    sourcemap: false
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error('Service worker build failed.');
  }
  const output = result.outputs[0];
  if (!output) throw new Error('Service worker build produced no output.');
  const code = await output.text();
  const banner = '/* Generated by scripts/build.ts from src/client/service-worker/sw.ts — do not edit by hand. */\n';
  await Bun.write('public/sw.js', `${banner}${code}`);
  return Buffer.byteLength(`${banner}${code}`);
}

/**
 * Runs the complete production build.
 *
 * @returns A summary of generated artifacts and their sizes.
 */
export async function buildAll(): Promise<{ serviceWorkerBytes: number; manifestVersion: string; precacheEntries: number }> {
  await build({
    configFile: 'vite.config.ts',
    logLevel: 'warn'
  });
  const serviceWorkerBytes = await buildServiceWorker();
  const assets = await buildAssets();
  return { serviceWorkerBytes, manifestVersion: assets.manifest.version, precacheEntries: assets.manifest.precache.length };
}

if (import.meta.main) {
  const started = Date.now();
  const summary = await buildAll();
  console.log(
    `build: vue bundle + sw.js (${(summary.serviceWorkerBytes / 1024).toFixed(1)} kB) + ${summary.precacheEntries} cache entries, version ${summary.manifestVersion} in ${Date.now() - started}ms`
  );
}
