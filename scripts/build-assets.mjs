function walk(directory, extension, output = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(full, extension, output);
    else if (!extension || entry.name.endsWith(extension)) output.push(full);
  }
  return output;
}

function iconNames() {
  const names = new Set(EXTRA_ICONS);
  const inventory = JSON.parse(readFileSync(ICON_INVENTORY, 'utf8'));
  for (const icon of inventory.icons || []) names.add(String(icon.name).replace(/^mdi-/, ''));
  for (const directory of [
    'design/auth/_generator',
    'design/icons/_generator',
    'design/admin-panel/_generator',
    'design/map-page/_generator'
  ]) {
    const absolute = path.join(ROOT, directory);
    if (!existsSync(absolute)) continue;
    for (const file of walk(absolute, '.py')) {
      for (const match of readFileSync(file, 'utf8').matchAll(/mdi-([a-z0-9-]+)/g)) {
        names.add(match[1]);
      }
    }
  }
  return [...names].sort();
}

function buildIconCss() {
  const source = readFileSync(MDI_CSS, 'utf8');
  const rules = new Map(
    [...source.matchAll(/\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"([^"]+)";/g)]
      .map((match) => [match[1], match[2]])
  );
  const lines = [
    '/* Generated by scripts/build-assets.mjs. Source: design/map-page/_generator/assets. */',
    '@font-face {',
    '  font-family: "Material Design Icons";',
    '  src: url("/assets/fonts/materialdesignicons-webfont.ttf") format("truetype");',
    '  font-weight: normal; font-style: normal; font-display: block;',
    '}',
    '.mdi::before {',
    '  display: inline-block; font: normal normal normal 24px/1 "Material Design Icons";',
    '  font-size: inherit; line-height: inherit; vertical-align: middle;',
    '  text-rendering: auto; -webkit-font-smoothing: antialiased;',
    '}',
    '.mdi { display: inline-flex; align-items: center; justify-content: center; }'
  ];
  const missing = [];
  for (const name of iconNames()) {
    const content = rules.get(name);
    if (!content) { missing.push(name); continue; }
    lines.push(`.mdi-${name}::before { content: "${content}"; }`);
  }
  if (missing.length) throw new Error(`Unknown MDI icons: ${missing.join(', ')}`);
  return `${lines.join('\n')}\n`;
}

function copyFonts() {
  mkdirSync(FONTS, { recursive: true });
  const sourceFonts = path.join(DESIGN_ASSETS, 'fonts');
  for (const name of readdirSync(sourceFonts)) {
    if (name.endsWith('.ttf')) copyFileSync(path.join(sourceFonts, name), path.join(FONTS, name));
  }
  copyFileSync(path.join(DESIGN_ASSETS, 'materialdesignicons-webfont.ttf'), path.join(FONTS, 'materialdesignicons-webfont.ttf'));
}

