function sha256(value) { return createHash('sha256').update(value).digest('hex'); }

function staticFiles() {
  const publicRoot = path.join(ROOT, 'public');
  const output = [];
  const add = (file) => {
    const absolute = path.join(publicRoot, file);
    if (existsSync(absolute) && statSync(absolute).isFile()) output.push(`/${file}`);
  };
  add('index.html');
  add('app.css');
  add('app.js');
  add('manifest.webmanifest');
  add('sw.js');
  for (const file of walk(path.join(publicRoot, 'js'), '.js')) {
    output.push(`/js/${path.relative(path.join(publicRoot, 'js'), file).split(path.sep).join('/')}`);
  }
  for (const file of walk(ASSETS, '')) {
    const relative = `/assets/${path.relative(ASSETS, file).split(path.sep).join('/')}`;
    if (!relative.endsWith('cache-manifest.json')) output.push(relative);
  }
  return [...new Set(output)].sort();
}

function writeManifest() {
  const files = staticFiles().filter((file) => file !== '/assets/cache-manifest.json');
  let hash = createHash('sha256');
  for (const file of files) hash.update(file).update(readFileSync(path.join(ROOT, 'public', file.slice(1))));
  const precache = ['/', ...files.filter((file) => file !== '/index.html')];
  const manifest = {
    version: hash.digest('hex').slice(0, 16),
    precache: [...new Set(precache)].sort(),
    runtime: { tileLimit: 256, apiCaching: false }
  };
  writeFileSync(path.join(ASSETS, 'cache-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

function main() {
  mkdirSync(ASSETS, { recursive: true });
  copyFonts();
  writeFileSync(path.join(ASSETS, 'icons.css'), buildIconCss());
  writeFileSync(path.join(ASSETS, 'logo.svg'), LOGO);
  writeFileSync(path.join(ASSETS, 'favicon.svg'), FAVICON);
  const manifest = writeManifest();
  console.log(`assets: ${manifest.precache.length} cache entries, version ${manifest.version}`);
}

main();
